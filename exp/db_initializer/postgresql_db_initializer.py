class RandomDataFactory:
    @staticmethod
    def generate_value(category: str) -> Any:
        if random.random() < NULL_PROBABILITY:
            return None

        category = category.upper()
        if category == "INTEGER":
            return random.randint(-10000, 10000)
        if category == "BIG_INTEGER":
            return random.randint(-(10 ** 12), 10 ** 12)
        if category == "FLOAT":
            return round(random.uniform(-10000.0, 10000.0), 2)
        if category == "DECIMAL":
            return Decimal(random.randint(-1000000, 1000000)) / Decimal(100)
        if category == "STRING":
            return RandomDataFactory._gen_string()
        if category in ("DATE", "TIMESTAMP", "TIME"):
            value = RandomDataFactory._gen_datetime()
            if category == "DATE":
                return value.date()
            if category == "TIME":
                return value.time()
            return value
        if category == "YEAR":
            return random.randint(1970, 2038)
        if category == "BINARY":
            return bytes(random.getrandbits(8) for _ in range(12))
        if category == "JSON":
            return json.dumps({
                "id": random.randint(1, 100),
                "tag": "".join(random.choices(string.ascii_lowercase, k=5)),
                "score": round(random.random(), 2),
            })
        raise ValueError(f"不支持的数据生成类别: {category}")

    @staticmethod
    def _gen_string() -> str:
        chars = string.ascii_letters + string.digits + " _-@"
        return "".join(random.choice(chars) for _ in range(random.randint(1, 50)))

    @staticmethod
    def _gen_datetime() -> datetime:
        end = datetime.now().replace(microsecond=0)
        start = end - timedelta(days=365 * 10)
        return start + timedelta(seconds=random.randint(0, int((end - start).total_seconds())))


class DatabaseInitializer:
    def __init__(self):
        self.columns_meta: List[Tuple[str, str, str]] = []
        self.executor = None

    def setup_database(self):
        if not isinstance(INITIAL_ROWS, int) or not 0 <= INITIAL_ROWS <= 2147483647:
            raise ValueError("INITIAL_ROWS 必须为 0 到 2147483647 之间的整数。")
        if not isinstance(BATCH_SIZE, int) or BATCH_SIZE <= 0:
            raise ValueError("BATCH_SIZE 必须为正整数。")
        if not 0 <= NULL_PROBABILITY <= 1:
            raise ValueError("NULL_PROBABILITY 必须在 0 到 1 之间。")
        self._prepare_columns_metadata()
        if BATCH_SIZE * (len(self.columns_meta) - 1) > 65535:
            raise ValueError("BATCH_SIZE 过大，单批绑定参数不能超过 PostgreSQL 的 65535 个限制。")

        from RL.db_executor import PostgreSQLExecutor

        try:
            logger.info("开始初始化 %s，目标行数: %s", QUALIFIED_TABLE, INITIAL_ROWS)
            self.executor = PostgreSQLExecutor(
                autoconnect=True,
                config=DB_CONFIG,
                query_timeout_seconds=DB_CONFIG.query_timeout,
            )

            with self.executor._conn.transaction():
                with self.executor._conn.cursor() as cursor:
                    self._recreate_table(cursor)
                    self._populate_data(cursor)
                    self._verify_row_count(cursor)
            logger.info("初始化完成：%s 已提交 %s 行数据。", QUALIFIED_TABLE, INITIAL_ROWS)
        except Exception:
            logger.exception("初始化失败，未提交的重建和插入操作已回滚。")
            raise
        finally:
            if self.executor is not None:
                self.executor.close()

    def _prepare_columns_metadata(self):
        self.columns_meta = list(COLUMN_DEFINITIONS)
        logger.info("元数据准备完成，共 %s 列（包含 id）。", len(self.columns_meta))

    def _recreate_table(self, cursor):
        cursor.execute(f"DROP TABLE IF EXISTS {QUALIFIED_TABLE};")
        col_defs = [f'  "{name}" {sql_type}' for name, sql_type, _ in self.columns_meta]
        create_sql = f"CREATE TABLE {QUALIFIED_TABLE} (\n" + ",\n".join(col_defs) + "\n)\n;"
        cursor.execute(create_sql)
        cursor.execute(
            f'ALTER TABLE {QUALIFIED_TABLE} ADD CONSTRAINT {PRIMARY_KEY_NAME} '
            'PRIMARY KEY ("id");'
        )
        logger.info("表结构创建完成。")

    def _populate_data(self, cursor):
        target_cols = [meta for meta in self.columns_meta if meta[0] != "id"]
        col_names = ", ".join(f'"{name}"' for name, _, _ in target_cols)
        batch_values = []
        total_inserted = 0

        for _ in range(INITIAL_ROWS):
            row = tuple(RandomDataFactory.generate_value(category) for _, _, category in target_cols)
            batch_values.append(row)
            if len(batch_values) >= BATCH_SIZE:
                self._insert_batch(cursor, col_names, batch_values)
                total_inserted += len(batch_values)
                batch_values = []
                logger.info("已写入 %s/%s 行（待事务提交）。", total_inserted, INITIAL_ROWS)

        if batch_values:
            self._insert_batch(cursor, col_names, batch_values)
            total_inserted += len(batch_values)
            logger.info("已写入 %s/%s 行（待事务提交）。", total_inserted, INITIAL_ROWS)

    def _insert_batch(self, cursor, col_names: str, values_list: List[tuple]):
        if not values_list:
            return
        row_placeholder = "(" + ", ".join(["%s"] * len(values_list[0])) + ")"
        placeholders = ", ".join([row_placeholder] * len(values_list))
        sql = f"INSERT INTO {QUALIFIED_TABLE} ({col_names}) VALUES {placeholders};"
        params = tuple(value for row in values_list for value in row)
        cursor.execute(sql, params)
        if cursor.rowcount != len(values_list):
            raise RuntimeError(f"批量插入行数异常: 预期 {len(values_list)}，实际 {cursor.rowcount}。")

    def _verify_row_count(self, cursor):
        cursor.execute(f"SELECT COUNT(*) AS row_count FROM {QUALIFIED_TABLE};")
        actual_rows = cursor.fetchone()["row_count"]
        if actual_rows != INITIAL_ROWS:
            raise RuntimeError(f"最终行数异常: 预期 {INITIAL_ROWS}，实际 {actual_rows}。")


